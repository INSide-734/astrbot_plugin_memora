function injectionLocaleCopy(index: 0 | 1 | 2): Record<string, string> {
  const entries = Object.entries(INJECTION_COPY).map(
    ([key, values]) => [key, values[index]] as const,
  );
  const normalizedReasonEntries = entries
    .filter(([key]) => key.startsWith("injection.reason."))
    .map(([key, value]) => {
      const suffix = key.slice("injection.reason.".length).toLowerCase();
      return [`injection.reason.${suffix}`, value] as const;
    });
  return Object.fromEntries([...entries, ...normalizedReasonEntries]);
}

